#!/usr/bin/env python3
"""Generate the branded Windows installer's colours, texts and artwork.

Inputs (single sources of truth):
  packages/ui/tokens.css            the generated Obsidian theme tokens (colours)
  apps/desktop/nsis/strings.json    every installer text in en / tr / de
  apps/desktop/icons/icon.png       the ghost mascot

Outputs (committed, small):
  apps/desktop/nsis/praxi-theme.nsh    colour defines for the NSIS code
  apps/desktop/nsis/praxi-strings.nsh  LangString definitions
  apps/desktop/nsis/art/ghost.bmp      the mascot tile on the page colour

Usage:
  python scripts/installer/generate_installer_assets.py          # rewrite outputs
  python scripts/installer/generate_installer_assets.py --check  # fail if they are stale

The two .nsh files need only the standard library, so --check runs anywhere. The bitmap needs
Pillow (pip install pillow); --check only verifies that the bitmap exists and has the right size.
"""
from __future__ import annotations

import argparse
import json
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NSIS = ROOT / "apps" / "desktop" / "nsis"
TOKENS = ROOT / "packages" / "ui" / "tokens.css"
STRINGS = NSIS / "strings.json"
ICON = ROOT / "apps" / "desktop" / "icons" / "icon.png"
GHOST = NSIS / "art" / "ghost.bmp"
GHOST_PX = 192  # shown at 64 px: 3x so it stays sharp up to 300% scaling

# (NSIS define name, CSS token)
COLOUR_TOKENS = [
    ("BG", "--color-background"),
    ("SURFACE", "--color-surface"),
    ("ELEVATED", "--color-surface-elevated"),
    ("TEXT", "--color-text"),
    ("TEXT2", "--color-text-secondary"),
    ("MUTED", "--color-text-muted"),
    ("FAINT", "--color-text-faint"),
    ("ACCENT", "--color-accent"),
    ("ACCENT_TEXT", "--color-accent-contrast"),
    ("DANGER", "--color-danger"),
    ("DANGER_TEXT", "--color-danger-contrast"),
    ("WARNING", "--color-warning"),
]

LANGS = [("en", "ENGLISH"), ("tr", "TURKISH"), ("de", "GERMAN")]
BOM = "﻿"


def read_tokens() -> dict[str, str]:
    css = TOKENS.read_text(encoding="utf-8")
    # The generated default theme (Obsidian) is the last block of the file.
    block = css.split("/* Generated default theme")[-1]
    out: dict[str, str] = {}
    for name, value in re.findall(r"(--[a-z0-9-]+):\s*(#[0-9a-fA-F]{6})\s*;", block):
        out.setdefault(name, value.lower())
    return out


def theme_nsh() -> str:
    tokens = read_tokens()
    lines = [
        "; GENERATED by scripts/installer/generate_installer_assets.py from packages/ui/tokens.css (Obsidian).",
        "; Do not edit by hand. RGB values feed SetCtlColors; BGR values feed Win32 COLORREF calls.",
    ]
    for name, token in COLOUR_TOKENS:
        if token not in tokens:
            raise SystemExit(f"token {token} not found in {TOKENS}")
        rgb = tokens[token][1:].upper()
        bgr = rgb[4:6] + rgb[2:4] + rgb[0:2]
        lines.append(f"!define PX_{name} {rgb}")
        lines.append(f"!define PX_{name}_BGR 0x{bgr}")
    return BOM + "\n".join(lines) + "\n"


def nsis_escape(value: str) -> str:
    # Only the characters that would end the string or start a line break need escaping;
    # $ is left alone on purpose: $PxOldVer and ${VERSION} are expanded by the installer.
    return value.replace("\n", "$\\r$\\n")


def load_strings() -> dict[str, dict[str, str]]:
    data = json.loads(STRINGS.read_text(encoding="utf-8"))
    return {k: v for k, v in data.items() if not k.startswith("_")}


def strings_nsh() -> str:
    lines = [
        "; GENERATED by scripts/installer/generate_installer_assets.py from strings.json.",
        "; Do not edit by hand.",
    ]
    for key, values in load_strings().items():
        for code, lang in LANGS:
            lines.append(f'LangString px_{key} ${{LANG_{lang}}} "{nsis_escape(values[code])}"')
    return BOM + "\n".join(lines) + "\n"


def ghost_bmp(bg_hex: str) -> bytes:
    from PIL import Image  # imported lazily: --check of the .nsh files needs no Pillow

    icon = Image.open(ICON).convert("RGBA").resize((GHOST_PX, GHOST_PX), Image.LANCZOS)
    bg = Image.new("RGBA", icon.size, "#" + bg_hex)
    bg.alpha_composite(icon)
    out = bg.convert("RGB")
    import io

    buf = io.BytesIO()
    out.save(buf, format="BMP")
    return buf.getvalue()


def bmp_size(path: Path) -> tuple[int, int]:
    head = path.read_bytes()[:26]
    width, height = struct.unpack("<ii", head[18:26])
    return width, abs(height)


def validate_strings() -> list[str]:
    problems: list[str] = []
    for key, values in load_strings().items():
        for code, _ in LANGS:
            text = values.get(code, "")
            if not text.strip():
                problems.append(f"{key}: missing {code}")
            if '"' in text:
                problems.append(f"{key}.{code}: contains an ASCII double quote")
        placeholders = {code: sorted(re.findall(r"\$PxOldVer|\$\{VERSION\}", values.get(code, ""))) for code, _ in LANGS}
        if len({tuple(v) for v in placeholders.values()}) != 1:
            problems.append(f"{key}: placeholders differ between languages {placeholders}")
    return problems


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are out of date")
    args = parser.parse_args()

    problems = validate_strings()
    if problems:
        print("\n".join(problems), file=sys.stderr)
        return 1

    outputs = {NSIS / "praxi-theme.nsh": theme_nsh(), NSIS / "praxi-strings.nsh": strings_nsh()}
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if not args.check:
                path.write_text(text, encoding="utf-8", newline="\n")
                print(f"wrote {path.relative_to(ROOT)}")

    if args.check:
        if not GHOST.exists() or bmp_size(GHOST) != (GHOST_PX, GHOST_PX):
            stale.append(GHOST)
    else:
        bg = read_tokens()["--color-background"][1:]
        GHOST.parent.mkdir(parents=True, exist_ok=True)
        data = ghost_bmp(bg)
        if not GHOST.exists() or GHOST.read_bytes() != data:
            GHOST.write_bytes(data)
            print(f"wrote {GHOST.relative_to(ROOT)}")

    if args.check and stale:
        names = ", ".join(str(p.relative_to(ROOT)) for p in stale)
        print(f"installer assets are stale: {names}\nrun: python scripts/installer/generate_installer_assets.py", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
